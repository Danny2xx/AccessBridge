"""Render EVALUATION.md from the live evaluation so its numbers never go stale.

Also reruns the default request on the Stage 0 straight-line proxy matrix, so the
document can show what moving to routed walking times changed.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from app.config import get_settings
from app.optimisation import optimise_from_stage0
from app.schemas import OptimisationRequest

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "EVALUATION.md"


def gbp(value: float) -> str:
    return f"GBP {value:,.0f}"


def num(value: float) -> str:
    return f"{value:,.0f}"


def signed(value: float) -> str:
    return f"{value:+,.0f}"


def proxy_comparison(request: OptimisationRequest) -> dict[str, Any]:
    result = optimise_from_stage0(request)
    comparison = result.accessibility
    assert comparison is not None
    return {
        "stops": len(result.selected_stops),
        "cost": result.total_cost_gbp,
        "reached": comparison.scenario.most_deprived_decile_population,
        "today": comparison.baseline.most_deprived_decile_population,
        "gain": comparison.delta_most_deprived_decile_population,
        "names": [stop.name for stop in result.selected_stops],
    }


def render(payload: dict[str, Any], routing: dict[str, Any], proxy: dict[str, Any]) -> str:
    default = payload["default"]
    request = default["request"]
    baseline = default["baseline"]
    scenario = default["scenario"]
    d1_gain = default["delta_most_deprived_decile_population"]
    b3_gain = default["delta_bottom_three_deciles_population"]
    total_gain = default["delta_total_population"]
    share_today = baseline["most_deprived_decile_population"] / max(1, baseline["total_population"])
    share_new = scenario["most_deprived_decile_population"] / max(1, scenario["total_population"])
    provenance = routing.get("routing_provenance", {})
    walk_only = routing.get("routing_profile") == "walk"

    lines: list[str] = []
    add = lines.append
    add("# Evaluation")
    add("")
    add("This file is generated by `scripts/write_evaluation.py` from the active")
    add("travel-time matrix, so the figures below always match the site and the API.")
    add("")
    if routing.get("source_mode") == "r5_input":
        add("The active matrix is routed with R5. Walking times follow the OpenStreetMap")
        add(
            f"street network ({provenance.get('osm_extract_name')}, {provenance.get('osm_extract_date')})"
        )
        if walk_only:
            add("at 80 metres a minute. Bus and Metro legs are not included, so a stop counts")
            add("as reached only on foot. The walk-plus-transit matrix from the same build is")
            add("saved beside it for comparison.")
        else:
            add(
                f"with bus and Metro from {provenance.get('gtfs_feed_name')} ({provenance.get('gtfs_feed_date')})."
            )
    else:
        add("The active matrix is proxy-derived from straight-line walking distance.")
    add("")
    add("Regenerate with:")
    add("")
    add("```bash")
    add(".venv/bin/python scripts/write_evaluation.py")
    add("```")
    add("")
    add("## 1. Default result")
    add("")
    add("Default request:")
    add("")
    add(f"- Budget: {gbp(request['budget_gbp'])}")
    add(f"- Maximum stops: {request['max_stops']}")
    add(f"- Catchment threshold: {request['threshold_min']} minutes")
    add(f"- Interchange required: {'yes' if request['require_interchange'] else 'no'}")
    add("")
    add("Solver result:")
    add("")
    add(f"- Status: {default['status']}")
    add(f"- Selected stops: {default['selected_stop_count']}")
    add(f"- Total cost: {gbp(default['total_cost_gbp'])}")
    add(f"- Objective value: {num(default['objective_value'])}")
    add("")
    add("Selected stop pattern:")
    add("")
    add("| Stop | Mode | Cost | Interchange |")
    add("|---|---|---:|---|")
    for stop in default["selected_stops"]:
        add(
            f"| {stop['name']} | {stop['mode_hint']} | {gbp(stop['cost_gbp'])} | {'yes' if stop['is_interchange'] else 'no'} |"
        )
    add("")
    add("## 2. Optimiser vs baseline")
    add("")
    add(
        f"Baseline definition: residents whose LSOA centroid is within {request['threshold_min']} active"
    )
    add("matrix minutes of a rail/Metro interchange candidate.")
    add("")
    add(
        f"Optimised definition: residents whose LSOA centroid is within {request['threshold_min']} active"
    )
    add("matrix minutes of at least one selected feeder candidate stop.")
    add("")
    add("| Metric | Baseline | AccessBridge | Delta |")
    add("|---|---:|---:|---:|")
    add(
        f"| Most-deprived-decile residents reached | {num(baseline['most_deprived_decile_population'])} | {num(scenario['most_deprived_decile_population'])} | {num(d1_gain)} |"
    )
    add(
        f"| Bottom-three-decile residents reached | {num(baseline['bottom_three_deciles_population'])} | {num(scenario['bottom_three_deciles_population'])} | {num(b3_gain)} |"
    )
    add(
        f"| Total population reached | {num(baseline['total_population'])} | {num(scenario['total_population'])} | {num(total_gain)} |"
    )
    add(
        f"| Share of reached residents in most-deprived decile | {share_today:.1%} | {share_new:.1%} | {(share_new - share_today) * 100:.1f} pp |"
    )
    cost = default.get("cost_per_d1_resident_gained_gbp")
    add(
        f"| Cost per most-deprived-decile resident gained | - | {'GBP ' + format(cost, '.2f') if cost else 'n/a'} | - |"
    )
    add("")
    add("The comparison is against today's rail and Metro reach alone. The stations stay,")
    add("so the new stops add to today's access rather than replacing it; bands that")
    add("show a negative delta lose nothing they have now.")
    add("")
    add("## 3. Equity distribution")
    add("")
    add("| IMD decile | Baseline population | AccessBridge population | Delta |")
    add("|---:|---:|---:|---:|")
    for row in default["decile_breakdown"]:
        add(
            f"| {row['imd_decile']} | {num(row['baseline_population'])} | {num(row['scenario_population'])} | {num(row['delta_population'])} |"
        )
    add("")
    add("## 4. Sensitivity analysis")
    add("")
    add("### Walk threshold sensitivity")
    add("")
    add(
        f"Budget and stop count are held at {gbp(request['budget_gbp'])} and {request['max_stops']} stops."
    )
    add("")
    add("| Threshold | Cost | Stops | D1 gain | Bottom-three gain | Total population delta |")
    add("|---:|---:|---:|---:|---:|---:|")
    for row in payload["threshold_sensitivity"]:
        add(
            f"| {row['request']['threshold_min']} min | {gbp(row['total_cost_gbp'])} | {row['selected_stop_count']} | {num(row['delta_most_deprived_decile_population'])} | {num(row['delta_bottom_three_deciles_population'])} | {num(row['delta_total_population'])} |"
        )
    add("")
    add("### Budget sensitivity")
    add("")
    add(
        f"Threshold and max stops are held at {request['threshold_min']} minutes and {request['max_stops']} stops."
    )
    add("")
    add("| Budget | Actual cost | Stops | D1 gain | Bottom-three gain | Total population delta |")
    add("|---:|---:|---:|---:|---:|---:|")
    for row in payload["budget_sensitivity"]:
        add(
            f"| {gbp(row['request']['budget_gbp'])} | {gbp(row['total_cost_gbp'])} | {row['selected_stop_count']} | {num(row['delta_most_deprived_decile_population'])} | {num(row['delta_bottom_three_deciles_population'])} | {num(row['delta_total_population'])} |"
        )
    add("")
    add("## 5. Routed walking times against the straight-line proxy")
    add("")
    add("The same default request on the Stage 0 proxy matrix, which estimated every walk")
    add("as a straight line at 80 metres a minute, gives a different picture of reach:")
    add("")
    add("| Matrix | Stops | Most-deprived reached | Reached today | Gain |")
    add("|---|---:|---:|---:|---:|")
    add(
        f"| Straight-line proxy | {proxy['stops']} | {num(proxy['reached'])} | {num(proxy['today'])} | {num(proxy['gain'])} |"
    )
    add(
        f"| Routed on streets (active) | {default['selected_stop_count']} | {num(scenario['most_deprived_decile_population'])} | {num(baseline['most_deprived_decile_population'])} | {num(d1_gain)} |"
    )
    add("")
    add("Real streets make walks longer, so both the baseline and the optimised reach")
    add("fall. The gain is the more robust figure, and the routed one is the one to quote.")
    add("")
    add("## 6. Reproducibility")
    add("")
    add("- Backend tests: `pytest` in the project root")
    add(
        "- Browser tests: `npm run test:e2e` in `frontend/`; they read expected figures from the API"
    )
    add("- `ruff`, `mypy`, the Python compile check and the frontend build are all clean")
    add("")
    add("Data provenance is recorded under `data/raw/provenance_stage0.json`,")
    add("`data/processed/stage0_*_metadata.json`, `data/processed/stage7_routing_metadata.json`")
    add("and `data/processed/r5_*_provenance.json`.")
    add("")
    return "\n".join(lines)


def main() -> None:
    from evaluate_phase2 import DEFAULT_REQUEST, evaluation_payload

    settings = get_settings()
    routing = json.loads(settings.stage7_routing_metadata_path.read_text())
    payload = evaluation_payload()
    proxy = proxy_comparison(DEFAULT_REQUEST)
    OUTPUT.write_text(render(payload, routing, proxy))
    default = payload["default"]
    print(
        json.dumps(
            {
                "reached": default["scenario"]["most_deprived_decile_population"],
                "today": default["baseline"]["most_deprived_decile_population"],
                "gain": default["delta_most_deprived_decile_population"],
                "stops": default["selected_stop_count"],
                "cost": default["total_cost_gbp"],
                "cost_per": default["cost_per_d1_resident_gained_gbp"],
                "total_reached": default["scenario"]["total_population"],
                "names": [s["name"] for s in default["selected_stops"]],
                "proxy": proxy,
            }
        )
    )


if __name__ == "__main__":
    import sys

    sys.path.insert(0, str(ROOT / "scripts"))
    main()
